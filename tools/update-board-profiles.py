"""Bundle public firmware board profiles for the Arduino SDK."""
import argparse
import json
from pathlib import Path
import re
from urllib.parse import quote
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]


def require(condition, message):
    if not condition:
        raise ValueError(message)


def fields(value, names, at):
    require(isinstance(value, dict) and set(value) == set(names), at + ': invalid fields')


def integer(value, low, high):
    return type(value) is int and low <= value <= high


def validate(bundle):
    """Reject unsupported formats or private hardware fields before replacing output."""
    fields(bundle, ('schema_version', 'boards'), 'profiles')
    require(type(bundle['schema_version']) is int and bundle['schema_version'] == 1, 'Unsupported profile schema')
    require(isinstance(bundle['boards'], list) and bool(bundle['boards']), 'Expected board profiles')
    identities = set()
    for profile in bundle['boards']:
        fields(profile, ('board', 'resources', 'motor_features', 'sensors'), 'board profile')
        board = profile['board']
        fields(board, ('model', 'revision'), 'board identity')
        require(integer(board['model'], 1, 255), 'Invalid board model')
        revision = board['revision']
        require(isinstance(revision, str) and re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', revision), 'Invalid board revision')
        require(all(int(v) <= 255 for v in revision.split('.')), 'Invalid board revision')
        identity = (board['model'], revision)
        require(identity not in identities, 'Duplicate board identity')
        identities.add(identity)
        resources = profile['resources']
        fields(resources, ('motors', 'encoders', 'gpio', 'status_leds'), 'resources')
        require(all(integer(v, 0, 255) for v in resources.values()), 'Invalid resource count')
        features = profile['motor_features']
        require(isinstance(features, list) and len(features) == resources['motors'], 'Motor feature count mismatch')
        for index, feature in enumerate(features):
            keys = ('id', 'current_sense', 'current_limit', 'fault_reporting')
            fields(feature, keys + (('current_limit_options',) if 'current_limit_options' in feature else ()), 'motor features')
            if 'current_limit_options' in feature:
                require(feature['current_limit'] is True, 'Options require current-limit hardware')
                options = feature['current_limit_options']
                fields(options, ('type', 'supported_thresholds_ma', 'can_disable'), 'current-limit options')
                require(options['type'] == 'discrete', 'Unsupported current-limit option type')
                require(type(options['can_disable']) is bool, 'Invalid can_disable flag')
                values = options['supported_thresholds_ma']
                require(isinstance(values, list) and 1 <= len(values) <= 255 and
                        all(integer(v, 1, 65535) for v in values) and values == sorted(set(values)),
                        'Invalid supported current-limit thresholds')
            require(type(feature['id']) is int and feature['id'] == index, 'Invalid motor ID')
            require(type(feature['current_sense']) is bool and type(feature['current_limit']) is bool and type(feature['fault_reporting']) is bool, 'Invalid motor features')
        fields(profile['sensors'], ('temperature', 'imu'), 'sensors')
        for kind, sensors in profile['sensors'].items():
            require(isinstance(sensors, list) and len(sensors) <= 255, 'Invalid sensor list')
            for index, sensor in enumerate(sensors):
                fields(sensor, ('id',) if kind == 'temperature' else ('id', 'accelerometer', 'gyroscope'), 'sensor')
                require(type(sensor['id']) is int and sensor['id'] == index, 'Invalid sensor ID')
                if kind == 'imu':
                    require(type(sensor['accelerometer']) is bool and type(sensor['gyroscope']) is bool, 'Invalid IMU features')
    return bundle


def generate(bundle):
    """Compile public JSON into fixed-size C++ records, with AVR tables in flash."""
    validate(bundle)
    boards = bundle['boards']
    motors = max(1, max(b['resources']['motors'] for b in boards))
    temperatures = max(1, max(len(b['sensors']['temperature']) for b in boards))
    imus = max(1, max(len(b['sensors']['imu']) for b in boards))
    thresholds = max([1] + [len(m.get('current_limit_options', {}).get('supported_thresholds_ma', [])) for b in boards for m in b['motor_features']])
    banner = '// Generated by tools/update-board-profiles.py. DO NOT EDIT.\n'
    header = banner + '''#ifndef KINISI_BOARD_PROFILES_H
#define KINISI_BOARD_PROFILES_H
#include <stdint.h>

enum class KinisiSensor : uint8_t { TEMPERATURE, IMU };
struct KinisiBoardResources { uint8_t motors, encoders, gpio, status_leds; };
/** Discrete nominal thresholds in milliamps; count delimits the supported values. */
struct KinisiCurrentLimitOptions { uint8_t threshold_count; uint16_t supported_thresholds_ma[THRESHOLD_CAPACITY]; bool can_disable; };
struct KinisiMotorFeatures { uint8_t id; bool current_sense, current_limit, fault_reporting; KinisiCurrentLimitOptions current_limit_options; };
struct KinisiImuFeatures { uint8_t id; bool accelerometer, gyroscope; };

/** Public hardware metadata; counts delimit valid entries in each array. */
struct KinisiBoardProfile {
    uint8_t model, major, minor, patch;
    KinisiBoardResources resources;
'''
    header = header.replace('THRESHOLD_CAPACITY', str(thresholds))
    header += f'    KinisiMotorFeatures motor_features[{motors}];\n'
    header += f'    uint8_t temperature_count, temperature_ids[{temperatures}];\n'
    header += f'    uint8_t imu_count;\n    KinisiImuFeatures imu[{imus}];\n'
    header += '''    /** Physical presence only; also check controller.supportsSensor before reading. */
    bool hasSensor(KinisiSensor kind, uint8_t index = 0) const {
        if (kind == KinisiSensor::TEMPERATURE) {
            for (uint8_t i = 0; i < temperature_count; ++i)
                if (temperature_ids[i] == index) return true;
        } else if (kind == KinisiSensor::IMU) {
            for (uint8_t i = 0; i < imu_count; ++i)
                if (imu[i].id == index) return true;
        }
        return false;
    }
};

/** Copy one exact profile into RAM; clear output and return false for unknown boards. */
bool kinisiLookupBoardProfile(uint8_t model, uint8_t major, uint8_t minor,
                             uint8_t patch, KinisiBoardProfile& output);
#endif
'''
    source = banner + '''#include "kinisi_board_profiles.h"
#include <stddef.h>
#if defined(__AVR__)
#include <avr/pgmspace.h>
#define KINISI_PROFILE_STORAGE PROGMEM
#else
#define KINISI_PROFILE_STORAGE
#endif

namespace {
const KinisiBoardProfile profiles[] KINISI_PROFILE_STORAGE = {
'''
    for board in boards:
        model = board['board']['model']
        revision = ', '.join(board['board']['revision'].split('.'))
        counts = ', '.join(str(board['resources'][key]) for key in ('motors', 'encoders', 'gpio', 'status_leds'))
        motors_output = []
        for m in board['motor_features']:
            options = m.get('current_limit_options', {})
            values = options.get('supported_thresholds_ma', [])
            option_value = '{' + f"{len(values)}, {{{', '.join(map(str, values)) or '0'}}}, {str(options.get('can_disable', False)).lower()}" + '}'
            motors_output.append('{' + f"{m['id']}, {str(m['current_sense']).lower()}, {str(m['current_limit']).lower()}, {str(m['fault_reporting']).lower()}, {option_value}" + '}')
        motor_values = ', '.join(motors_output) or '{}'
        temp = board['sensors']['temperature']
        temp_values = ', '.join(str(s['id']) for s in temp) or '0'
        imu = board['sensors']['imu']
        imu_values = ', '.join('{' + f"{s['id']}, {str(s['accelerometer']).lower()}, {str(s['gyroscope']).lower()}" + '}'
                               for s in imu) or '{}'
        source += (f'    {{{model}, {revision}, {{{counts}}}, {{{motor_values}}}, '
                   f'{len(temp)}, {{{temp_values}}}, {len(imu)}, {{{imu_values}}}}},\n')
    source += '''};
}

bool kinisiLookupBoardProfile(uint8_t model, uint8_t major, uint8_t minor,
                             uint8_t patch, KinisiBoardProfile& output) {
    for (size_t i = 0; i < sizeof(profiles) / sizeof(profiles[0]); ++i) {
        KinisiBoardProfile candidate;
#if defined(__AVR__)
        memcpy_P(&candidate, &profiles[i], sizeof(candidate));
#else
        candidate = profiles[i];
#endif
        if (candidate.model == model && candidate.major == major &&
            candidate.minor == minor && candidate.patch == patch) {
            output = candidate;
            return true;
        }
    }
    output = {};
    return false;
}
'''
    return {'kinisi_board_profiles.h': header, 'kinisi_board_profiles.cpp': source,
            'tools/board_profiles.json': json.dumps(bundle, indent=2) + '\n'}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument('--profiles', type=Path, help='Generated firmware include/board_profiles.json')
    source.add_argument('--branch', help='Explicit firmware branch or tag to import')
    parser.add_argument('--check', action='store_true', help='Check generated files without writing')
    args = parser.parse_args(argv)
    if args.profiles is not None:
        raw = args.profiles.read_text(encoding='utf-8-sig')
    else:
        url = ('https://raw.githubusercontent.com/szolotykh/kinisi-motor-controller-firmware/' +
               quote(args.branch, safe='') + '/include/board_profiles.json')
        with urlopen(url, timeout=30) as response:
            raw = response.read().decode('utf-8-sig')
    outputs = generate(json.loads(raw))  # Validate all metadata before touching any output.
    for name, content in outputs.items():
        path = ROOT / name
        if args.check:
            require(path.exists() and path.read_text(encoding='utf-8') == content,
                    'Stale generated board profile file: ' + name)
        else:
            with path.open('w', encoding='utf-8', newline='\n') as output:
                output.write(content)
    print('Board profiles up to date' if args.check else 'Generated bundled board profiles')


if __name__ == '__main__':
    main()
